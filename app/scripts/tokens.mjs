import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

export const tokensPath = resolve('../docs/design-system/tokens.json');
export const outputPath = resolve('src/styles/_tokens.scss');

export function renderTokens(tokens) {
  const variables = [
    ...tokens.color.tokens,
    ...tokens.spacing.tokens,
    ...tokens.fontSize.tokens,
    ...tokens.radius.tokens,
    ...tokens.shadow.tokens,
    ...tokens.motion.tokens,
  ].map(({ name, value }) => `  --${name}: ${value};`);
  const families = Object.entries(tokens.type.families).map(
    ([name, value]) => `  --font-${name}: ${value};`,
  );
  const typeClasses = tokens.type.groups.flatMap((group) =>
    group.styles.map((style) => {
      const family = style.family ?? group.family;
      const rules = [
        `font-family: var(--font-${family})`,
        `font-size: ${style.fontSize}`,
        `line-height: ${style.lineHeight}`,
        `font-weight: ${style.fontWeight}`,
        style.letterSpacing && `letter-spacing: ${style.letterSpacing}`,
      ].filter(Boolean);
      return `.t-${style.name} {\n${rules.map((rule) => `  ${rule};`).join('\n')}\n}`;
    }),
  );
  return [
    '// Generated by scripts/tokens.mjs from docs/design-system/tokens.json. Run `npm run tokens`.',
    `:root {\n${[...variables, ...families].join('\n')}\n}`,
    ...typeClasses,
    '',
  ].join('\n\n');
}

export function readTokens() {
  return JSON.parse(readFileSync(tokensPath, 'utf8'));
}

if (process.argv[1]?.endsWith('tokens.mjs')) {
  writeFileSync(outputPath, renderTokens(readTokens()));
}
